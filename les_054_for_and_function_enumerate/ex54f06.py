# Операторы break, continue и else в цикле for
# Внутри оператора цикла for можно так же, как и в цикле while, прописывать операторы break и continue, а также добавлять блок else. 
# Смысл их работы абсолютно тот же самый:

# оператор break прерывает работу цикла;
# оператор continue пропускает одну итерацию цикла;
# блок else содержит операторы, выполняющиеся после штатного завершения цикла for.
# Давайте рассмотрим несколько примеров использования ключевых слов break, continue и else внутри for. Начнем с оператора break.

# Пусть имеется список из чисел, в котором требуется найти первое значение больше семи. Программу можно реализовать следующим образом:

# numbers = [1, 3, 5, 7, 9, 11, 9, 13, -5]

# for num in numbers:
