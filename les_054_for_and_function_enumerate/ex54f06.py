#         continue  # пропускаем короткие слова
#     if len(word) > 10:
#         break

#     print(word)
# else:
#     print("В списке были обработаны все слова.")

                  
# После запуска этой программы увидим результат:

# добрые
# циклы

# Здесь оператор continue пропускает слова меньше 5 символов, оператор break прерывает цикл for при обнаружении слова более 10 символов, 
# а блок else служит для вывода строки:

# "В списке были обработаны все слова."
                  
# в случае штатного завершения работы цикла for.

words = ["кот", "добрые", "дом", "циклы", "окно", "программирование"]

for word in words:
    if len(word) < 5:
        continue  # пропускаем короткие слова
    if len(word) > 10:
        break

    print(word)
else:
    print("В списке были обработаны все слова.")

