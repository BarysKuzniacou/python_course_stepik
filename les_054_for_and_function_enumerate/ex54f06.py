# операторы break и/или continue, в другой обходятся без них. В конечном итоге, нужно стремиться, чтобы итоговый текст программы получался 
# понятным, читабельным, а сама программа расходовала как можно меньше памяти и выполнялась как можно быстрее. Это основные критерии написания 
