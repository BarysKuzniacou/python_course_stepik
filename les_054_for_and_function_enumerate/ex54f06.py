#         print(f"Найдено первое число больше 7: {num}")
#         break
#     print(f"Проверяем: {num}")

                  
# Получим следующий результат ее работы:

# Проверяем: 1
# Проверяем: 3
# Проверяем: 5
# Проверяем: 7
# Найдено первое число больше 7: 9

# Как видите, при срабатывании оператора break, оператор цикла for полностью завершает свою работу и управление передается следующему 
# оператору, стоящему после цикла (в данном случае программа просто завершается).

numbers = [1, 3, 5, 7, 9, 11, 9, 13, -5]

for num in numbers:
    if num > 7:
        print(f"Найдено первое число больше 7: {num}")
        break
    print(f"Проверяем: {num}")


# Давайте модифицируем эту программу и будем дополнительно выводить строку, что искомый элемент не найден в случае его отсутствия в списке. 
# Это можно сделать путем добавления блока else для цикла for:

# numbers = [1, 3, 5, 7, 9, 11, 9, 13, -5]

# for num in numbers:
