# Если сейчас запустить программу, то результат вывода не изменится, т.к. цикл for завершается оператором break, то есть, не штатно. 
# А вот если изменить список numbers, убрав из него все числа больше 7:

# numbers = [1, 3, 5, 7]

                  
# то увидим следующий результат вывода:

# Проверяем: 1
# Проверяем: 3
# Проверяем: 5
# Проверяем: 7
# Искомый элемент не найден!

# То есть, функция print(), записанная в блоке else, выполняется только при штатном завершении работы цикла for.

numbers = [1, 3, 5, 7]

for num in numbers:
    if num > 7:
        print(f"Найдено первое число больше 7: {num}")
        break
    print(f"Проверяем: {num}")
else:
    print("Искомый элемент не найден!")


# Следующий пример показывает возможность использования оператора continue внутри тела цикла for. Пусть имеется список со следующими значениями:

# data = [10, -11, 20, 6.5, None, -10, 0, 7, None, None]

                  
# Требуется пропускать значения None и вычислять сумму только неотрицательных чисел. Реализовать это можно следующим образом:

# s = 0
# for x in data:
#     if x is None or x < 0:
#         continue

#     s += x

# print(s)

                  
# Здесь записано условие, в котором проверяется, что текущее значение элемента списка data равно либо None, либо меньше 0. Если это 
# так, то выполняется оператор continue, который пропускает все ниже стоящие операторы в теле цикла на текущей итерации. После чего 
# цикл продолжается с переходом к следующему значению списка.

data = [10, -11, 20, 6.5, None, -10, 0, 7, None, None]

s = 0
for x in data:
    if x is None or x < 0:
        continue

    s += x

print(s)

# Конечно, все эти операторы break, continue и else можно использовать совместно в рамках одного цикла. Покажем это на примере вывода 
# слов от 5 символов и более, но при обнаружении слова более 10 символов цикл будет прерываться:

